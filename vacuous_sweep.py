#!/usr/bin/env python3
"""
vacuous_sweep.py — «ни один гейт не проходит ВХОЛОСТУЮ» (TK-0067). ОБЩИЙ для трёх скиллов.

ТРЕТИЙ ЭТАЖ мета-стражей, и разница между этажами существенна:
  покрытие      — «у гейта ЕСТЬ фикстура»;
  страж фикстур — «фикстура НЕ инертна» (её вход реально создан);
  этот свип     — «гейт не утверждает ПОЛОЖИТЕЛЬНОГО о работе, которой НЕ делал».

ЗАЧЕМ СВИПОМ, А НЕ СПИСКОМ ИМЁН. TK-0002 («ноль проверок неотличим от нуля нарушений») закрыли
починкой девяти ПОИМЁННО названных гейтов — и класс вернулся в НОВОМ коде: три гейта, написанные
позже, печатали «подделанных слов не найдено», «каждый DOI ведёт в названную работу», «каждая
❓-цель заведена» на НЕСУЩЕСТВУЮЩЕМ пути (TK-0066). Дефект, закрытый одноразовым ДЕЙСТВИЕМ,
возвращается (TK-0016): носитель обязан стоять КЛАССОМ ВЫШЕ дефекта. Поэтому — цикл, а не перечень,
и поэтому же инструмент ОДИН на три скилла, а не копия в каждом selftest: три копии предиката
разъедутся ровно так же, как разъезжались два детектора вердиктов.

ЧТО СЧИТАЕТСЯ ЧЕСТНЫМ — ДВА зонда, и ни один не опирается на формулировку.
  первый  — несуществующий путь: честен тот, кто вышел НЕНУЛЕВЫМ кодом;
  второй  — существующий, но ПУСТОЙ выпуск: честен тот, кто, выйдя нулём, НАЗВАЛ ЧИСЛО осмотренного.
Никакой конвенции формулировки больше нет, и это не упрощение, а починка.

Прежде честность засчитывалась ещё и по ФРАЗЕ из списка «нечего/пропускаю/корпус пуст». Фраза искалась
ПОДСТРОКОЙ по всему выводу, без границы слова и без привязки к строке-итогу, — то есть служебная
строка вроде «пропускаю дотфайлы» легализовала любое последующее «✅ всё проверено». Хуже: конвенция
превращала в ЗАЧЁТ уже открытый дефект, который дословно на неё и опирался (TK-0049 — «корпус пуст —
сверять нечего» на неверном пути). Признак честности, который можно удовлетворить фразой, — не
признак (TK-0079).

Цена перехода мала, и это ИЗМЕРЕНО. Но число надо назвать точно, потому что первая его версия была
получена прежним, однозондовым пробником — тем самым, который этот же переход объявляет негодным.
По честному счёту (новый зонд, старое дерево) на фразе держались три гейта, ещё три УХОДИЛИ В ОБХОД
и потому вовсе не отвечали, а остальные 35 честны по коду возврата. Из этих 35 десять честны только
ТРЕЙСБЕКОМ, а не внятным отказом: планка тут пол, а не потолок, и «честен» здесь значит ровно «не
приписал себе работу», а не «ответил хорошо».

Заметим разницу: «ноль объектов в НАСТОЯЩЕМ выпуске» — законный зелёный, и ПЕРВЫЙ зонд его не трогает,
потому что подаёт несуществующий путь. Именно этот случай и разбирает ВТОРОЙ зонд, и вопрос там не
«зелено ли», а «видно ли, что осмотрено ноль» (TK-0105).

ПЛАНКА НИЗКАЯ ОСОЗНАННО: свип не судит, ВЕРЕН ли вывод гейта, — только что гейт не приписывает себе
непроделанную работу. Это пол, не потолок.

ИСПОЛЬЗОВАНИЕ:
    vacuous_sweep.py <scripts_dir> [--exclude имя:причина ...] [--also имя ...]
                                   [--argv имя:причина:аргументы ...]   # {tmp} → временная папка
    vacuous_sweep.py --selftest      # двусторонняя самопроверка предиката, без обхода файлов
"""

import argparse
import atexit
import glob
import os
import re
import shutil
import subprocess
import sys
import tempfile

# ВТОРОЙ ЗОНД: существующий, валидный ПО ФОРМЕ, но пустой выпуск. Первый зонд (несуществующий путь)
# ловит «гейт работает там, где работать не с чем»; этот — «гейт зеленеет, НЕ СКАЗАВ, сколько осмотрел».
# Разница между ними принципиальная: ноль объектов в настоящем выпуске — законный исход, и вопрос не в
# том, зелено ли, а в том, ВИДНО ЛИ, что осмотрено ноль.
#
# ПРИЗНАК — ЧИСЛО, и это не третья конвенция-фраза, а ровно то, чего не хватало прежней: число нельзя
# удовлетворить формулировкой, оно не зависит от языка и его нельзя произнести, не посчитав. Прежде
# гейты говорили правду словами («посценных отчётов нет»), и правда эта была неотличима от
# универсального утверждения о непроверенном («каждое утверждение прозы стоит на названном источнике»).
# Замер перед правкой: из 36 опрошенных гейтов 15 отказывались, 5 называли число, 16 зеленели без него —
# и лишь ТРИ из шестнадцати утверждали свойство вместо пустоты. Значит правило дёшево: тринадцати
# достаточно дописать число к уже сказанному, а три — настоящие дефекты.
EMPTY_EPISODE_DIRS = ("_factcheck/REPORTS", "_factcheck/AGENT_RUNS", "источники/_txt")
# Путь, которого заведомо нет. Вырожденный вход выбран самый однозначный: для ЛЮБОГО гейта — хоть
# файлового, хоть папочного — несуществующий путь не даёт оснований ни для какого положительного
# утверждения, поэтому исключений «а мне такой вход законен» тут не бывает.
NONEXISTENT = "/nonexistent-vacuous-sweep-probe-path"
# Порог берётся из окружения, чтобы фикстура на ЗАВИСАНИЕ не ждала минуту: без этого её пришлось бы
# либо не писать, либо растягивать суиту — и класс остался бы без стража.
TIMEOUT_SEC = int(os.environ.get("VACUOUS_TIMEOUT", "60"))


# Обрыв РАЗБОРА АРГУМЕНТОВ — не отказ гейта. Гейт с двумя обязательными аргументами, получив один,
# умирает на арности, путей НЕ ТРОГАЕТ и отдаёт ненулевой код — а свип засчитывал это как честность.
# Под этой ширмой три релизных гейта не просто зеленели на несуществующих путях, а уходили обходить
# диск (TK-0077). Поэтому зонд подбирает арность, а usage-обрыв доказательством не считает.
# Маркеры на ДВУХ языках, и это не мелочь: по языковому контракту пакета литеральные строки вывода
# русские, поэтому обрыв арности сплошь и рядом печатается как «использование:». Английского списка
# хватало ровно на argparse; собственный usage гейта проходил мимо, зонд не поднимал арность и
# засчитывал честность по прогону, до работы не дошедшему, — то есть ровно то, что этот же
# инструмент объявляет недоказательством. Живой носитель — check_comments бильд-редактора.
# ОСТАЮЩИЙСЯ ПРЕДЕЛ, названный вслух: это по-прежнему признак-фраза, а не структура, и потому он
# держится на языке. Правильнее спрашивать арность у самого argparse; пока — TK-0106.
USAGE_MARKERS = (
    "usage:",
    "использование:",
    "error: the following arguments",
    "error: unrecognized arguments",
)
MAX_PROBE_ARITY = 3


def looks_like_usage(code, output):
    """Гейт не принял АРГУМЕНТЫ — значит до работы не дошёл и ничего о своей честности не сказал."""
    return code != 0 and any(marker in output.lower() for marker in USAGE_MARKERS)


def not_vacuous(code, output):
    """Вакуум = вышел НУЛЁМ на несуществующем пути. Чистая функция: свип обязан быть проверяем НА СЕБЕ,
    иначе он способен пройти вхолостую сам — что и было бы смешно."""
    return code != 0


def states_scope(code, output, probe_path=""):
    """Названо ли КАКОЕ-НИБУДЬ число в зелёном выводе на пустом выпуске.

    Из вывода вычёркивается сам путь зонда: временный каталог содержит цифры, и без этого признак
    удовлетворялся бы эхом пути — то есть снова чем угодно, кроме счёта.

    СМОТРИМ ВЕСЬ ВЫВОД, А НЕ ИТОГОВУЮ СТРОКУ, и это осознанный размен. «Итог — последняя строка» —
    ложное допущение: `build_index` печатает сводку ПЕРЕД таблицей, `check_issues` заканчивает
    advisory-хвостом, и обоих такой признак объявлял бы дефектными. Ложное срабатывание тут дороже
    пропуска: оно учит игнорировать инструмент. Планка поэтому нарочно низкая — «гейт вообще
    произносит какое-то количество». Три настоящих дефекта (универсальное утверждение о непроверенном:
    «каждая сцена…», «каждое утверждение…», «нечитаемых нет») не содержали ни одной цифры и ловятся;
    гейт, спрятавший ноль за посторонним числом, — не ловится, и это записано как предел, а не забыто.

    ПРЕДЕЛ, НАЗВАННЫЙ КОНКРЕТНО. У гейта с НЕСКОЛЬКИМИ зелёными утверждениями свип не стережёт ни одно
    из них по отдельности: `check_corpus` судит и об именах, и о качестве OCR, и число одной ветки
    прикрывает другую. Счёт там дописан к обеим, но удержать его мутацией нельзя — снятие любого одного
    оставляет цифру соседа, а снятие обоих ломает модуль, что доказывает не то. Так что здесь работает
    не механизм, а правило чтения диффа: у КАЖДОГО зелёного утверждения своё число по своему множеству.
    """
    if code != 0:
        return True
    body = (output or "").replace(probe_path, " ")
    if not body.strip():
        return False
    return bool(re.search(r"\d", body))


def predicate_selftest():
    """Двусторонняя проверка самого предиката. Без неё свип — незастрахованный страж."""
    cases = [
        (not_vacuous, 1, "✗ нарушение", True, "ненулевой код — не вакуум"),
        (
            not_vacuous,
            0,
            "✅ корпус пуст — сверять нечего",
            False,
            "ФРАЗА больше не оправдывает — ВАКУУМ",
        ),
        (
            not_vacuous,
            0,
            "✅ каждый DOI ведёт в названную работу.",
            False,
            "универсальное — ВАКУУМ",
        ),
        (not_vacuous, 0, "", False, "молчаливый нулевой выход — ВАКУУМ"),
        (looks_like_usage, 2, "usage: check_x.py <a> <b>", True, "обрыв арности — не ответ гейта"),
        (looks_like_usage, 1, "✗ нарушение найдено", False, "настоящий отказ — не обрыв арности"),
        (looks_like_usage, 0, "✅ всё хорошо", False, "нулевой выход обрывом арности не бывает"),
        (states_scope, 1, "✗ нарушение", True, "отказ область называть не обязан"),
        (states_scope, 0, "✅ отчётов: 0 — сверять нечего", True, "число названо — область видна"),
        (
            states_scope,
            0,
            "✅ каждое утверждение стоит на источнике",
            False,
            "свойство вместо счёта",
        ),
        (states_scope, 0, "", False, "молчание областью не является"),
    ]
    bad = 0
    for predicate, code, out, want, desc in cases:
        got = predicate(code, out)
        if got == want:
            print(f"  ✅ предикат: {desc}")
        else:
            print(f"  ❌ предикат СЛОМАН: {desc} — ждали {want}, получили {got}")
            bad += 1
    return bad


def _empty_args(episode, arities):
    """Аргументы ВТОРОГО зонда по арности — по сигнатуре, принятой в пакете.

    Подавать один и тот же путь N раз было нельзя: у двухаргументных гейтов второй аргумент — ПАПКА
    КОРПУСА, и корень выпуска на его месте контракт корпуса законно отвергает. В итоге починка обхода
    закрыла зонду доступ к зелёной ветке ровно тех трёх гейтов, ради которых зонд и писался: свип
    видел отказ и печатал «честен», а на настоящем пустом корпусе они утверждали «каждый… проверен»
    о нуле объектов.
    """
    reports = os.path.join(episode, "_factcheck", "REPORTS")
    corpus = os.path.join(episode, "источники")
    return [reports, corpus, episode][:arities] if arities > 1 else [episode]


def _probe(script, args, extra):
    """Один прогон зонда с ГОТОВЫМ списком аргументов. (код, вывод) или (None, "") на таймаут."""
    try:
        run = subprocess.run(
            [sys.executable, script, *args, *extra],
            capture_output=True,
            text=True,
            timeout=TIMEOUT_SEC,
        )
    except subprocess.TimeoutExpired:
        return None, ""
    return run.returncode, run.stdout + run.stderr


def _probe_arity(script, probe_path, extra):
    """Подобрать арность и вернуть (код, вывод, арность). Обрыв разбора аргументов ответом не считаем,
    поэтому поднимаем число путей, пока гейт не дойдёт до работы. Арность потом переиспользует ВТОРОЙ
    зонд: подбирать её дважды значило бы завести две копии одного правила.

    ПЕРЕБИРАЮТСЯ ВСЕ АРНОСТИ, А НЕ ПЕРВАЯ ОТВЕТИВШАЯ. Прежняя редакция останавливалась, как только
    гейт переставал ронять usage, — и потому не видела гейта, ЧЕСТНОГО при одном аргументе и
    ВАКУУМНОГО при двух. Живой носитель: `check_identifier_exists` брал вторым позиционным каталог
    кэша, и эта ветка обходила единственную проверку пути, так что на двух несуществующих путях он
    печатал «разрешено 0 из 0 DOI ✅ сверять нечего» нулевым кодом. Свип объявлял его честным.
    Правило простое: гейт обязан отказывать на несуществующем пути при КАЖДОЙ арности, которую он
    принимает; поэтому зелёный ход сообщается сразу, а честный запоминается лишь как запасной.
    Радиус измерен перед заменой, а не предположен: полный перебор по трём скиллам поднимает ровно
    те гейты, что и раньше, — новых обвинений ноль."""
    code = out = None
    answered = None
    for arities in range(1, MAX_PROBE_ARITY + 1):
        code, out = _probe(script, [probe_path] * arities, extra)
        if code is None:
            return None, "", arities
        if looks_like_usage(code, out):
            continue
        if code == 0:
            return code, out, arities  # вакуум — докладываем именно о нём
        if answered is None:
            answered = (code, out, arities)
    return answered if answered else (code, out, MAX_PROBE_ARITY)


def parse_exclusions(items):
    """`имя:причина`. Причина ОБЯЗАТЕЛЬНА: исключение без причины — это поблажка, а поблажку
    в списке исключений не отличить от разбора (первый вариант свипа вывел из-под него
    `check_issues` ровно потому, что тот мешал, — и на перепроверке оказался дефектным)."""
    out = {}
    for item in items or []:
        name, _, reason = item.partition(":")
        if not reason.strip():
            print(f"✗ исключение без причины: {item!r} — пиши `имя:почему это законно`")
            sys.exit(2)
        out[name.strip()] = reason.strip()
    return out


def main():
    ap = argparse.ArgumentParser(description="ни один гейт не проходит вхолостую")
    ap.add_argument("scripts_dir", nargs="?", help="папка скриптов скилла")
    ap.add_argument("--exclude", action="append", metavar="ИМЯ:ПРИЧИНА")
    ap.add_argument("--also", action="append", metavar="ИМЯ", help="не-check_* скрипт под свип")
    ap.add_argument(
        "--argv",
        action="append",
        metavar="ИМЯ:ПРИЧИНА:АРГУМЕНТЫ",
        help="обязательные опции гейта, без которых он не доходит до работы; {tmp} — временная папка",
    )
    ap.add_argument("--selftest", action="store_true", help="только самопроверка предиката")
    args = ap.parse_args()

    if args.selftest:
        return 1 if predicate_selftest() else 0
    if not args.scripts_dir:
        print("usage: vacuous_sweep.py <scripts_dir> [--exclude имя:причина] | --selftest")
        return 2
    if not os.path.isdir(args.scripts_dir):
        print(f"✗ vacuous_sweep: папки скриптов нет — {args.scripts_dir}")
        return 2

    # РЕЦЕПТ ЗОНДА, а не поблажка. Гейт с обязательной опцией (`--cache`) не доходит до работы ни на
    # какой арности, и у свипа ровно два выхода: вывести его из-под проверки или научиться подавать
    # опцию. Первое — исключение, то есть слепое пятно; второе — рецепт, после которого гейт судится
    # наравне со всеми. Разница принципиальная, поэтому это отдельный ключ, а не ещё один --exclude.
    # Причина ОБЯЗАТЕЛЬНА и здесь, наравне с исключением. Ревью: рецепт задумывался строже исключения
    # («гейт остаётся под судом»), а вышел мягче — причины не требовал и в отчёте не печатался, то есть
    # слепое пятно не исчезло, а переехало в менее подотчётный ключ. Рецепт виден в вердикте, и его
    # можно оспорить, как оспаривают исключение.
    extra_argv, argv_reason = {}, {}
    probe_tmp = None
    for item in args.argv or []:
        name, _, rest = item.partition(":")
        reason, _, arguments = rest.partition(":")
        if not reason.strip() or not arguments.strip():
            print(
                f"✗ рецепт зонда без причины или без аргументов: {item!r} — пиши `имя:почему:аргументы`"
            )
            return 2
        if "{tmp}" in arguments and probe_tmp is None:
            # Временная папка создаётся ЛЕНИВО: безусловный `mkdtemp` оставлял по каталогу на каждый
            # прогон свипа (одиннадцать за один selftest, сотни за сессию, тысячи за полную мутацию).
            probe_tmp = tempfile.mkdtemp(prefix="vacuous-sweep-")
            atexit.register(shutil.rmtree, probe_tmp, True)
        extra_argv[name.strip()] = [
            piece.replace("{tmp}", probe_tmp or "") for piece in arguments.split() if piece
        ]
        argv_reason[name.strip()] = reason.strip()
    # Имя папки зонда — БЕЗ ЦИФР, и вычитаются оба уровня. `mkdtemp` даёт случайный суффикс, в котором
    # цифры бывают, а бывают и нет; гейт, печатающий basename (домашний идиом пакета), подсовывал эти
    # цифры предикату вместо счёта. Вердикт свипа начинал зависеть от случайного имени: 37 зелёных из
    # 40 прогонов одного и того же вакуумного гейта. Мигающий страж хуже пропуска — он учит
    # перезапускать до зелёного.
    probe_root = tempfile.mkdtemp(prefix="vacuous-probe-")
    atexit.register(shutil.rmtree, probe_root, True)
    empty_episode = os.path.join(probe_root, "пустой-выпуск-зонда")
    for relative in EMPTY_EPISODE_DIRS:
        os.makedirs(os.path.join(empty_episode, relative), exist_ok=True)
    excluded = parse_exclusions(args.exclude)
    targets = sorted(glob.glob(os.path.join(args.scripts_dir, "check_*.py")))
    for name in args.also or []:
        path = os.path.join(args.scripts_dir, name if name.endswith(".py") else name + ".py")
        if os.path.isfile(path) and path not in targets:
            targets.append(path)
    if not targets:
        # Сам свип не имеет права пройти вхолостую — это было бы совсем уж по теме.
        print(
            f"✗ vacuous_sweep: в {args.scripts_dir} не найдено ни одного check_*.py — свипать нечего, "
            "и молча зеленеть на этом нельзя"
        )
        return 2

    # ИСКЛЮЧЕНИЕ, КОТОРОЕ НИ ВО ЧТО НЕ ЦЕЛИТ, — тот же дефект, что исключение без причины, и он ХУЖЕ:
    # причину хотя бы видно, а промах цели не видно вовсе. Итог считался как len(targets)-len(excluded),
    # поэтому каждая фантомная строка молча ЗАНИЖАЛА число осмотренных гейтов: research рапортовал
    # «3 гейтов, вакуумных нет», просвипав 5 (две ссылки были на гейты соседнего скилла). Инструмент,
    # который стоит верхним этажом и специально ловит «claim о непроделанной работе», не может сам
    # печатать заниженный отчёт. Найдено независимым ревью.
    known = {os.path.basename(p)[:-3] for p in targets}
    phantom = sorted((set(excluded) | set(extra_argv)) - known)
    if phantom:
        print(
            f"✗ vacuous_sweep: исключение без цели в {args.scripts_dir}: {', '.join(phantom)} — "
            "такого гейта здесь нет (ссылка на соседний скилл? опечатка?); молча занижать счёт нельзя"
        )
        return 2

    bad = 0
    swept = 0
    unreached = 0
    for path in targets:
        name = os.path.basename(path)[:-3]
        if name in excluded:
            print(f"  ⓘ {name}: исключён — {excluded[name]}")
            continue
        # АРИТНОСТЬ ПОДБИРАЕТСЯ. Гейт, которому нужны два пути, на одном умирает разбором аргументов —
        # это не ответ о его честности, а отказ его выслушать. Пробуем 1, 2, 3 несуществующих пути и
        # судим по ПЕРВОМУ прогону, который до работы дошёл.
        code, out, arities = _probe_arity(path, NONEXISTENT, extra_argv.get(name, []))
        timed_out = code is None
        # Зонд СОСТОЯЛСЯ в обоих исходах, поэтому счётчик растёт до разбора: иначе зависание всех целей
        # печаталось как «не осмотрено ни одного гейта, все исключены» с кодом 2 — то есть самый тяжёлый
        # диагноз (обход диска) выдавался за непригодную папку, да ещё с ложной причиной. В инструменте
        # против ложных рапортов о работе это особенно неуместно.
        swept += 1
        if timed_out:
            print(f"  ❌ {name}: не ответил за {TIMEOUT_SEC}с на несуществующих путях — это ОБХОД")
            bad += 1
            continue
        if looks_like_usage(code, out):
            bad += 1
            print(
                f"  ❌ {name}: ни на одной арности до {MAX_PROBE_ARITY} не дошёл до работы — "
                "свип не смог его опросить, а молча считать это честностью нельзя"
            )
        elif not_vacuous(code, out):
            # ВТОРОЙ ЗОНД — пустой, но настоящий выпуск. Первый доказал, что гейт не работает там, где
            # работать не с чем; этот спрашивает, ВИДНО ЛИ по зелёной строке, сколько он осмотрел.
            scope_code, scope_out = _probe(
                path, _empty_args(empty_episode, arities), extra_argv.get(name, [])
            )
            scope_out = scope_out.replace(probe_root, " ") if scope_out else scope_out
            recipe = f" (зонд по рецепту: {argv_reason[name]})" if name in argv_reason else ""
            if scope_code is None:
                bad += 1
                print(f"  ❌ {name}: не ответил за {TIMEOUT_SEC}с на ПУСТОМ выпуске — это обход")
            elif looks_like_usage(scope_code, scope_out) or scope_code != 0:
                # ТРЕТИЙ ИСХОД, названный отдельно. Гейт отказал или не принял аргументы — значит про
                # его ЗЕЛЁНУЮ ветку зонд ничего не узнал. Считать это «областью названа» нельзя: ровно
                # так первый зонд когда-то засчитывал обрыв арности за честность. Отсутствие проверки и
                # пройденная проверка обязаны быть РАЗНЫМИ строками отчёта.
                unreached += 1
                print(
                    f"  ⓘ {name}: второй зонд не достал — гейт отказал на пустом выпуске "
                    f"({(scope_out or '').strip().splitlines()[0][:70] if scope_out.strip() else 'молча'})"
                )
            elif states_scope(scope_code, scope_out, empty_episode):
                print(f"  ✅ {name}: не утверждает положительного о непроделанной работе{recipe}")
            else:
                bad += 1
                last = [ln for ln in scope_out.split("\n") if ln.strip()]
                print(
                    f"  ❌ {name}: на ПУСТОМ выпуске зеленеет, не назвав ЧИСЛА осмотренного\n"
                    f"       напечатал: {(last[-1] if last else '(молча)')[:140]}\n"
                    "       чинить так: в итоговой строке назвать счёт («отчётов: 0», «осмотрено 0»).\n"
                    "       Ноль — законный исход; невидимый ноль неотличим от универсального утверждения."
                )
        else:
            bad += 1
            print(
                f"  ❌ {name}: вышел НУЛЁМ на несуществующем пути (класс TK-0002/TK-0066)\n"
                f"       напечатал: {out.strip()[:140]}\n"
                "       чинить так: несуществующий путь — отказ с ненулевым кодом. Ноль объектов в\n"
                "       НАСТОЯЩЕМ выпуске остаётся законным зелёным: свип зондирует не его."
            )
    # Свип не имеет права пройти вхолостую САМ, и проверка стоит ПОСЛЕ исключений: прежде она стояла до
    # них, поэтому при полном исключении целей печаталось «0 гейтов, вакуумных нет» и код 0 — ровно тот
    # предикат, ради которого инструмент заведён, нарушенный им самим (TK-0080).
    if not swept:
        print(
            f"✗ vacuous_sweep: в {args.scripts_dir} не осмотрено НИ ОДНОГО гейта "
            f"(целей {len(targets)}, все исключены) — ноль осмотренных неотличим от нуля вакуумных"
        )
        return 2
    if bad:
        print(f"✗ вакуумных гейтов: {bad} — ноль проверок неотличим от нуля нарушений")
        return 1
    tail = f"; второй зонд не достал до {unreached}" if unreached else ""
    print(f"✅ свип вырожденного входа: осмотрено {swept} гейтов, вакуумных нет{tail}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
